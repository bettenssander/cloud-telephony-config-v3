// Vertaalt de vaste tekst van index.html (tekst, placeholder, title, alt, aria-label) naar het Frans.
function i18nStatic() {
  document.documentElement.lang = LANG;
  if (LANG !== "fr") return;
  // <option> zonder value gebruikt zijn tekst als waarde: eerst de Nederlandse tekst als waarde vastzetten
  document.querySelectorAll("option:not([value])").forEach(function (o) {
    o.setAttribute("value", o.textContent.trim());
  });
  var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT),
    nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(function (n) {
    var pn = n.parentNode.nodeName;
    if (pn === "SCRIPT" || pn === "STYLE") return;
    var m = /^(\s*)([\s\S]*?)(\s*)$/.exec(n.nodeValue);
    if (m[2] && Object.prototype.hasOwnProperty.call(FR, m[2])) n.nodeValue = m[1] + FR[m[2]] + m[3];
  });
  document.querySelectorAll("[placeholder],[title],[alt],[aria-label]").forEach(function (e) {
    ["placeholder", "title", "alt", "aria-label"].forEach(function (a) {
      var v = e.getAttribute(a);
      if (v && Object.prototype.hasOwnProperty.call(FR, v)) e.setAttribute(a, FR[v]);
    });
  });
  document.title = tx(document.title);
}
i18nStatic();
